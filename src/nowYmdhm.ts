import dayjs from 'dayjs';

/********************************************************************************************************************
 * 현재 년월일시분을 YYYYMMDDHHmm 형식의 숫자로 반환하는 함수
 * ******************************************************************************************************************/
export function nowYmdhm(): number {
  return Number(dayjs().format('YYYYMMDDHHmm'));
}

export default nowYmdhm;
